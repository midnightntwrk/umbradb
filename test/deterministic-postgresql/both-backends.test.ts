import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { encodeRow } from "../../src/determinism/cbor.js";
import {
  COLUMN_TYPE_RULES,
  type ConsistentRead,
  catalogRelations,
  catalogTables,
  columnVerdict,
  databaseRefusals,
  keyOrderTerm,
  PINNED_SETTINGS,
  refusalMessage,
  TABLE_RULES,
} from "../../src/deterministic-postgresql/index.js";
import { startPglite } from "../determinism/pglite-database.js";
import { startPostgres, type TestDatabase, type TestServer } from "../determinism/postgres-database.js";

/**
 * A138 (task 2.2a, owner decision Q69): the component's rules give the same results on PostgreSQL 17 and on PGlite
 * 0.5.10 — read side by side from one fixture on each backend, through the database API's read handles, and compared
 * with each other: the catalog facts the rules read, every refusal with its message (one case of every refused row of
 * `design.md` §4's column-type table and of every refusal of its paragraph), DT-2's byte order of text keys, and the
 * pinned session settings with the texts they make PostgreSQL print. Each case's own message is checked against the
 * design's words in `column-rules.test.ts` and `column-refusals.test.ts`; here the two backends must agree byte for byte.
 */

const FIXTURE = `
  CREATE SCHEMA m;
  CREATE TYPE m.mood AS ENUM ('sad', 'ok');
  CREATE DOMAIN m.positive AS integer CHECK (VALUE > 0);
  CREATE TYPE m.pair AS (a integer, b text);
  CREATE TABLE m.allowed (
    id bigint PRIMARY KEY, t text COLLATE "und-x-icu", v varchar(8), u uuid, b boolean, j jsonb, n numeric(20),
    bytes bytea, a integer[], d text DEFAULT lower('X'), g bigint GENERATED ALWAYS AS (id * 2) STORED
  );
  CREATE TABLE m.no_key (a integer);
  CREATE TABLE m.numeric_key (k numeric PRIMARY KEY);
  CREATE TABLE m.jsonb_key (k jsonb PRIMARY KEY);
  CREATE TABLE m.array_key (k integer[] PRIMARY KEY);
  CREATE TABLE m.types (
    id integer PRIMARY KEY, scaled numeric(38,2), r real, dp double precision, tstz timestamptz, ts timestamp,
    dt date, tm time, ttz timetz, iv interval, js json, ch char(4), mo money, en m.mood, dom m.positive,
    comp m.pair, ip inet, rng int4range, moods m.mood[]
  );
  CREATE TABLE m.defaults (
    id integer PRIMARY KEY,
    always_id integer GENERATED ALWAYS AS IDENTITY,
    default_id integer GENERATED BY DEFAULT AS IDENTITY,
    s serial,
    at text DEFAULT now()::text,
    stamp text DEFAULT CURRENT_TIMESTAMP::text,
    who text DEFAULT CURRENT_USER,
    rand bigint DEFAULT (random() * 10)::bigint,
    uid uuid DEFAULT gen_random_uuid(),
    doc jsonb DEFAULT JSON_OBJECT('a': 1 RETURNING jsonb)
  );
  CREATE SEQUENCE m.counter;
  CREATE UNLOGGED TABLE m.scratch (id integer PRIMARY KEY);
  CREATE TABLE m.text_keys (k text COLLATE "und-x-icu" PRIMARY KEY);
  INSERT INTO m.text_keys VALUES ('b'), ('ä'), ('B'), ('a');
  CREATE TABLE m.varchar_keys (k varchar(4) COLLATE "und-x-icu" PRIMARY KEY);
  INSERT INTO m.varchar_keys VALUES ('b'), ('ä'), ('B'), ('a');
  CREATE TABLE m.time_keys (k timestamptz PRIMARY KEY);
  INSERT INTO m.time_keys VALUES ('2025-05-21 14:30:01+00'), ('2025-05-21 16:30:00.5+02'), ('1969-12-31 23:59:59.5+00'),
    ('2025-05-21 14:30:00+00'), ('0001-01-01 00:00:00+00'), ('9999-12-31 23:59:59.999999+00'), ('1970-01-01 00:00:00+00');
`;

interface Backend {
  readonly name: string;
  server?: TestServer;
  db?: TestDatabase;
}

const BOTH: readonly Backend[] = [{ name: "PostgreSQL 17" }, { name: "PGlite 0.5.10" }];

beforeAll(async () => {
  const [postgres, pglite] = BOTH as [Backend, Backend];
  postgres.server = await startPostgres();
  pglite.server = await startPglite();
  for (const backend of BOTH) {
    backend.db = await (backend.server as TestServer).create();
    await backend.db.exec(FIXTURE);
  }
}, 180_000);

afterAll(async () => {
  for (const backend of BOTH) await backend.server?.stop();
}, 60_000);

/** Runs `body` on each backend through the database API's read handle, in `BOTH`'s order. */
async function onBoth<T>(body: (read: ConsistentRead) => Promise<T>): Promise<[T, T]> {
  const results: T[] = [];
  for (const backend of BOTH) results.push(await (backend.db as TestDatabase).read(body));
  return results as [T, T];
}

describe("A138: the component's rules give the same results on PostgreSQL 17 and PGlite 0.5.10", () => {
  it("reads the same catalog facts on both", async () => {
    const [postgres, pglite] = await onBoth(async (read) => ({
      tables: await catalogTables(read),
      relations: await catalogRelations(read),
    }));
    expect(postgres.tables.map((table) => table.name)).toEqual([
      "allowed",
      "array_key",
      "defaults",
      "jsonb_key",
      "no_key",
      "numeric_key",
      "scratch",
      "text_keys",
      "time_keys",
      "types",
      "varchar_keys",
    ]);
    expect(pglite).toEqual(postgres);
  });

  it("refuses the same tables, sequences and columns with the same codes and messages on both", async () => {
    const [postgres, pglite] = await onBoth(async (read) => {
      const tables = await catalogTables(read);
      const refusals = databaseRefusals(tables, await catalogRelations(read));
      const refusedRules = tables.flatMap((table) =>
        table.columns.flatMap((column) => {
          const verdict = columnVerdict(column);
          return verdict.allowed ? [] : [`${verdict.rule.id} ${verdict.code}`];
        }),
      );
      return {
        messages: refusals.map(({ refusal, place }) => refusalMessage(refusal, place)),
        codes: [...new Set(refusals.map(({ refusal }) => refusal.code))].sort(),
        refusedRules: [...new Set(refusedRules)].sort(),
      };
    });
    expect(pglite.messages).toEqual(postgres.messages);
    // Not vacuous: every refusal code, every refused row of the column-type table, every key refusal and every
    // refusal of the paragraph is among them.
    expect(postgres.codes).toEqual([
      "no-primary-key",
      "non-deterministic-column",
      "non-deterministic-table",
      "unsupported-column-type",
      "unsupported-key-type",
    ]);
    const refusedRows = COLUMN_TYPE_RULES.filter((rule) => !rule.allowed).map((rule) => `${rule.id} ${rule.allowed ? "" : rule.code}`);
    const keyRows = ["array", "jsonb", "numeric"].map((id) => `${id} unsupported-key-type`);
    expect(postgres.refusedRules).toEqual([...refusedRows, ...keyRows].sort());
    for (const rule of Object.values(TABLE_RULES)) {
      expect(postgres.messages.some((message) => message.includes(rule.what)), rule.what).toBe(true);
    }
    expect(postgres.messages.length).toBeGreaterThan(30);
    expect(postgres.messages.filter((message) => message.includes('table "m"."allowed"'))).toEqual([]);
  });

  it("lists schemas and tables by the bytes of their names, a partitioned table once, on both", async () => {
    // Written after the mutation pass of task 2.2a: the fixture above has only lower-case names and no partition, so
    // a catalog read in locale order, or one listing partitions, passed the suite.
    const lists: string[][] = [];
    for (const backend of BOTH) {
      const db = await (backend.server as TestServer).create();
      await db.exec(`
        CREATE SCHEMA m;
        CREATE SCHEMA "Z";
        CREATE TABLE m.a (id integer PRIMARY KEY);
        CREATE TABLE "Z"."é" (id integer PRIMARY KEY);
        CREATE TABLE "Z".b (id integer PRIMARY KEY);
        CREATE TABLE "Z"."B" (id integer PRIMARY KEY);
        CREATE TABLE "Z".parted (id integer PRIMARY KEY) PARTITION BY RANGE (id);
        CREATE TABLE "Z".parted_1 PARTITION OF "Z".parted FOR VALUES FROM (0) TO (10);
        CREATE TABLE "Z".parted_2 PARTITION OF "Z".parted FOR VALUES FROM (10) TO (20);
      `);
      const tables = await db.read((read) => catalogTables(read));
      lists.push(tables.map((table) => `${table.schema}.${table.name}${table.partitioned ? " (partitioned)" : ""}`));
    }
    // UTF-8 bytes: "Z" 5a < "m" 6d; "B" 42 < "b" 62 < "parted" 70 … < "é" c3 a9. The partitions are part of "parted".
    expect(lists[0]).toEqual(["Z.B", "Z.b", "Z.parted (partitioned)", "Z.é", "m.a"]);
    expect(lists[1]).toEqual(lists[0]);
  });

  it("orders text and varchar keys by their bytes with the key's ORDER BY term on both, whatever the collation", async () => {
    for (const [table, type] of [
      ["text_keys", "text"],
      ["varchar_keys", "character varying"],
    ] as const) {
      const sql = `SELECT k FROM m.${table} ORDER BY ${keyOrderTerm("k", type)}`;
      const [postgres, pglite] = await onBoth((read) => read.query(sql));
      // UTF-8 bytes: "B" 42 < "a" 61 < "b" 62 < "ä" c3 a4.
      expect(postgres.map((row) => row.k), type).toEqual(["B", "a", "b", "ä"]);
      expect(pglite).toEqual(postgres);
      // Control: the column's own collation orders them otherwise, so the term is what makes the order.
      const [own] = await onBoth((read) => read.query(`SELECT k FROM m.${table} ORDER BY k`));
      expect(own.map((row) => row.k)).not.toEqual(["B", "a", "b", "ä"]);
    }
    expect(keyOrderTerm("id", "bigint")).toBe('"id"');
    expect(keyOrderTerm("at", "timestamp with time zone")).toBe('"at"');
    expect(keyOrderTerm('a"b', "text")).toBe('"a""b" COLLATE "C"');
  });

  it("orders timestamptz keys by time with the key's ORDER BY term on both: the order of their encoded integers", async () => {
    const sql = `SELECT k FROM m.time_keys ORDER BY ${keyOrderTerm("k", "timestamp with time zone")}`;
    const [postgres, pglite] = await onBoth((read) => read.query(sql));
    // By time (Q74): before 1970 first, a fraction after its whole second, 16:30:00.5+02 as 14:30:00.5Z.
    expect(postgres.map((row) => row.k)).toEqual([
      "0001-01-01T00:00:00Z",
      "1969-12-31T23:59:59.5Z",
      "1970-01-01T00:00:00Z",
      "2025-05-21T14:30:00Z",
      "2025-05-21T14:30:00.5Z",
      "2025-05-21T14:30:01Z",
      "9999-12-31T23:59:59.999999Z",
    ]);
    expect(pglite).toEqual(postgres);
    // DT-1's integers of the same values, read back from their CBOR heads, increase in that order.
    const integers = postgres.map((row) => {
      const bytes = encodeRow([row.k], ["timestamp with time zone"]).subarray(1);
      const head = bytes[0] as number;
      const argument = (head & 0x1f) < 24 ? BigInt(head & 0x1f) : BigInt(`0x${Buffer.from(bytes.subarray(1)).toString("hex")}`);
      return head >> 5 === 1 ? -1n - argument : argument;
    });
    for (let i = 1; i < integers.length; i++) expect((integers[i] as bigint) > (integers[i - 1] as bigint)).toBe(true);
    // Control: the values the API returns, sorted as text, put a fraction before its whole second ("." 2e < "Z" 5a).
    const keys = postgres.map((row) => row.k as string);
    expect([...keys].sort()).not.toEqual(keys);
  });

  it("pins the same session settings on both, so PostgreSQL prints each value the same", async () => {
    const settings = PINNED_SETTINGS.map(([name], index) => `current_setting('${name}') AS s${index}`).join(", ");
    const [postgres, pglite] = await onBoth(async (read) => ({
      settings: await read.query(`SELECT ${settings}`),
      texts: await read.query(`
        SELECT '\\x00ff'::bytea::text AS bytes, '2026-10-23 10:00:00.123456+00'::timestamptz::text AS stamp,
               '2026-10-23'::date::text AS day, '1 day 2 hours'::interval::text AS span,
               0.1::double precision::text AS double, 0.1::real::text AS single`),
    }));
    expect(postgres.settings).toEqual([Object.fromEntries(PINNED_SETTINGS.map(([, value], index) => [`s${index}`, value]))]);
    expect(postgres.texts).toEqual([
      {
        bytes: "\\x00ff",
        stamp: "2026-10-23 10:00:00.123456+00",
        day: "2026-10-23",
        span: "1 day 02:00:00",
        double: "0.1",
        single: "0.1",
      },
    ]);
    expect(pglite).toEqual(postgres);
  });
});
